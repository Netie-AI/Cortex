DEMOS = {"crm": (_CRM_OBJECTS, _CRM_LINKS, _CRM_ACTIONS)}


def scaffold_demo(name: str, *, packs_root: Path | str | None = None, overwrite: bool = False) -> Path:
    objs, links, actions = DEMOS[name]
    return scaffold_pack(
        name,
        object_types_yaml=objs,
        link_types_yaml=links,
        action_types_yaml=actions,
        packs_root=packs_root,
        overwrite=overwrite,
    )


def _read_trio(src: Path) -> dict[str, str]:
    out = {}
    for key in ("object_types", "link_types", "action_types"):
        out[f"{key}_yaml"] = (src / f"{key}.yaml").read_text(encoding="utf-8")
    fpath = src / "functions.yaml"
    if fpath.is_file():
        out["functions_yaml"] = fpath.read_text(encoding="utf-8")
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Scaffold a new Cortex pack from an ontology trio.")
    parser.add_argument("--name", help="pack name (lower_snake)")
    parser.add_argument("--from-dir", help="dir with object_types/link_types/action_types.yaml")
    parser.add_argument("--demo", choices=sorted(DEMOS), help="scaffold a built-in demo pack")
    parser.add_argument("--packs-root", default=None, help="override packs/ root (tests)")
    parser.add_argument("--overwrite", action="store_true")
    args = parser.parse_args(argv)

    if args.demo:
        pack = scaffold_demo(args.demo, packs_root=args.packs_root, overwrite=args.overwrite)
    elif args.name and args.from_dir:
        pack = scaffold_pack(
            args.name, packs_root=args.packs_root, overwrite=args.overwrite, **_read_trio(Path(args.from_dir))
        )
    else:
        parser.error("give --demo NAME, or --name NAME --from-dir DIR")
    print(f"scaffolded pack: {pack}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
